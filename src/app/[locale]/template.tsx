/**
 * Переход между страницами.
 *
 * `template.tsx` создаётся заново на каждой навигации — в отличие от макета,
 * который переживает переходы. Поэтому содержимое страницы проявляется,
 * а не подменяется мгновенно, и переход перестаёт выглядеть как рывок.
 *
 * Анимируется только прозрачность. Сдвиг здесь ставить нельзя: `transform`
 * на предке делает его точкой отсчёта для `position: fixed`, и модальные
 * окна внутри страницы поехали бы вместе с содержимым.
 */
export default function Template({ children }: { children: React.ReactNode }) {
  return <div className="animate-page-in">{children}</div>;
}
