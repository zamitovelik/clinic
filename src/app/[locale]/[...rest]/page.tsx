import { notFound } from "next/navigation";

/**
 * Ловушка для несуществующих адресов.
 *
 * Без неё Next.js на неизвестный адрес отдавал свою стандартную заглушку —
 * английскую, без шапки, подвала и хоть какой-то ссылки обратно. Наша
 * страница 404 лежит внутри языкового сегмента, и чтобы она сработала,
 * несовпавший адрес должен сначала попасть в этот сегмент.
 *
 * Настоящие маршруты этот перехватчик не затрагивает: точное совпадение
 * и обычные динамические сегменты всегда имеют преимущество перед
 * «остатком пути».
 */
export default function CatchAllNotFound(): never {
  notFound();
}
